#!/usr/bin/env python3
"""Build assets/schema.js from a GSA/dcat-us checkout (jsonschema/definitions).

Usage: python3 tools/build-schema.py /path/to/dcat-us/jsonschema/definitions <commit>

Writes a trimmed, editor-oriented summary of each DCAT-US 3.0 class: its
properties, their labels, help text, requirement level, widget kind, whether
they hold several values, and which classes a class-valued field may hold.
Standard library only.
"""
import json, os, sys

SRC, COMMIT = sys.argv[1], sys.argv[2]
SLUG_TO_CLASS = {}
schemas = {}
for f in sorted(os.listdir(SRC)):
    if not f.endswith(".json"):
        continue
    s = json.load(open(os.path.join(SRC, f), encoding="utf-8"))
    name = f[:-5]
    schemas[name] = s
    SLUG_TO_CLASS[s["$id"].rstrip("/").split("/")[-1]] = name

TEXTAREA = {"description", "abstract", "versionNotes", "liabilityStatement", "purpose",
            "scopeNote", "restrictionNote", "definition", "bibliographicCitation", "endpointDescription",
            "provenance", "geometry"}
# Classes that the schema allows as a plain string as well as an object. The editor treats
# them as text (Concept: a label; Identifier: the identifier string).
STRING_CLASSES = {"Concept", "Identifier"}

def walk(node, fn):
    if isinstance(node, dict):
        fn(node)
        for k, v in node.items():
            if k in ("_oldDocs", "examples"):
                continue
            walk(v, fn)
    elif isinstance(node, list):
        for v in node:
            walk(v, fn)

def summarize(cls, p):
    refs, types, fmts, enums = [], set(), set(), []
    patterns = []
    def fn(n):
        if "$ref" in n:
            r = n["$ref"]
            refs.append(cls if r == "#" else SLUG_TO_CLASS[r.rstrip("/").split("/")[-1]])
        t = n.get("type")
        if isinstance(t, str): types.add(t)
        elif isinstance(t, list): types.update(t)
        if "format" in n: fmts.add(n["format"])
        if "enum" in n: enums.append([(n.get("description") or "Options").split(",")[0].split(" see ")[0].strip(), n["enum"]])
        if "pattern" in n: patterns.append(n["pattern"])
    walk(p, fn)
    refs = sorted(set(refs))
    multi = "array" in types
    out = {}
    if refs and not set(refs) <= STRING_CLASSES:
        out["kind"] = "link"
        out["classes"] = refs
        # An Organization has the one property an Agent requires (name), and no class in the
        # schema forbids extra properties, so an Agent-typed field accepts an Organization too.
        if refs == ["Agent"]:
            out["classes"] = ["Agent", "Organization"]
    elif refs:
        out["kind"] = refs[0].lower()  # concept | identifier
    elif enums:
        out["kind"] = "enum"
        out["groups"] = enums
        out["patterns"] = patterns
    elif "date" in fmts or "date-time" in fmts:
        out["kind"] = "date"
    elif "iri" in fmts:
        out["kind"] = "iri"
    elif patterns and "mailto" in patterns[0]:
        out["kind"] = "email"
        out["pattern"] = patterns[0]
    elif "object" in types:
        out["kind"] = "json"  # GeoJSON / bbox: shown as text
        multi = False
    elif "number" in types:
        out["kind"] = "text"
    else:
        out["kind"] = "text"
    if multi:
        out["multi"] = True
    return out

out = {"commit": COMMIT, "classes": {}}
for name, s in schemas.items():
    props_src = s.get("properties")
    if props_src is None:  # Concept, Identifier: string-or-object
        for alt in s.get("anyOf", []):
            if alt.get("type") == "object":
                props_src = alt.get("properties", {})
    required = list(s.get("required", []))
    props = []
    for pname, p in (props_src or {}).items():
        if pname in ("@id", "@type"):
            continue
        lvl = p.get("requirementLevel", "Optional")
        if pname in required:
            lvl = "Mandatory"
        info = summarize(name, p)
        if info["kind"] == "text" and pname in TEXTAREA:
            info["kind"] = "textarea"
        title = p.get("title") or pname
        props.append(dict(n=pname, label=title[:1].upper() + title[1:],
                          help=(p.get("description") or "").strip(),
                          lvl={"Mandatory": "req", "Recommended": "rec"}.get(lvl, "opt"), **info))
    out["classes"][name] = {"desc": s.get("description", ""), "required": required, "props": props}

js = ("/* Generated by tools/build-schema.py from GSA/dcat-us jsonschema/definitions @ " + COMMIT +
      ". Do not edit by hand. */\nwindow.DCATUS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "assets", "schema.js"), "w", encoding="utf-8").write(js)
print("wrote assets/schema.js", len(js), "bytes,", len(out["classes"]), "classes")
