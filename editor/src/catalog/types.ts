/**
 * One object in a storage-independent DCAT graph. IDs may be temporary source locations
 * immediately after import; a WorkspaceCatalog guarantees that they are stable UUIDs.
 */
export interface CatalogObject {
  /**
   * The object's identity within this graph. Immediately after decomposition this is a
   * deterministic JSON Pointer URI fragment (`#` is the root and
   * `#/dataset/0/distribution/1` a distribution). A workspace replaces these
   * source-location IDs with stable browser-generated UUIDs. Treat the value as opaque:
   * it is graph identity, not the object's DCAT `@id`, which remains in `properties`.
   */
  id: string
  /**
   * The DCAT-US 3.0 class the schema allows where the object sits. Its `@type` only
   * chooses among several, or names a subclass (an Organization where an Agent is
   * allowed). The top level's class comes from its `@type`.
   */
  dcatClass: string
  /** Every property that is not a link, unknown ones included, with values exactly as read. */
  properties: Record<string, unknown>
  /** Class-valued properties: property name → child IDs, in source order. */
  links: Record<string, string[]>
  /** Link properties whose source value was one object rather than an array, so export can write them back the same way. */
  singleLinks: string[]
}

/** Shared graph shape used from decomposition through editing and export. */
export interface CatalogGraph {
  /**
   * The root object's ID. After decomposition this is `#`; a workspace replaces
   * it with the root object's stable UUID.
   */
  rootObjectId: string
  /** Every object by ID, in document order after decomposition (each parent before its children). */
  objects: Map<string, CatalogObject>
}

/** Stable catalog identity assigned when an imported graph becomes a workspace. */
export type CatalogId = string
export type CatalogRevision = number

/** Canonical application workspace after an imported graph receives stable identities. */
export interface WorkspaceCatalog {
  /**
   * Stable identity of the working catalog itself, separate from the root Catalog object's
   * ID and its DCAT `@id`. Generated by Inventory and preserved across metadata edits.
   */
  id: CatalogId
  /**
   * Version of the DCAT-US schema used to interpret this workspace, such as `3.0.0`.
   * This is schema metadata, not the catalog's own DCAT `version` property.
   */
  schemaVersion: string
  /**
   * Repository revision on which this workspace is based. A successful graph-changing save
   * advances it; the repository rejects saves based on a stale revision.
   */
  revision: CatalogRevision
  /** Editable DCAT object graph, whose object IDs are stable UUIDs in a workspace. */
  graph: CatalogGraph
}
